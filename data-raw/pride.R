.pride_alias_dict <- c(
  purrr::set_names(names(.pride)),
  purrr::imap(.pride, \(palette, name) {
    aliases <- palette[["aliases"]]
    setNames(rep(name, times = length(aliases)), aliases)
  }) |>
    purrr::compact() |>
    purrr::list_c()
)

# Ensure that all names and aliases are lowercase and contain underscores only
checkmate::assert_character(
  names(.pride_alias_dict),
  pattern = "^[a-z0-9_]+$"
)

tags <- purrr::map(.pride, \(palette) {
  palette[["tags"]]
})

.pride_tag_dict <- split(
  rep(names(.pride), lengths(tags)),
  purrr::list_c(tags)
)

.pride_size_dict <- split(
  names(.pride),
  purrr::map_int(.pride, \(palette) {
    length(palette[["colors"]])
  })
)

.pride <- .pride |>
  purrr::imap(\(palette, name) {
    structure(
      palette[["colors"]],
      name = name,
      # TODO: Are aliases and tags even necessary at this point?
      aliases = palette[["aliases"]],
      tags = palette[["tags"]],
      class = "lgbtq_palette"
    )
  }) |>
  structure(class = "lgbtq_palette_list")

usethis::use_data(
  .pride, .pride_alias_dict, .pride_tag_dict, .pride_size_dict,
  internal = TRUE, overwrite = TRUE
)
